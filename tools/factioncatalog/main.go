// Command factioncatalog generates the WoW 1.12.1 (build 5875) faction
// template table the classic modules use to classify units as hostile,
// neutral or friendly. It reads FactionTemplate.dbc from a cMaNGOS Classic
// server (tmp/client-data-5875), verifies its pinned checksum, and never
// accesses the network or server internals. Run from the repository root:
//
//	./run factioncatalog:generate
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"errors"
	"fmt"
	"go/format"
	"os"

	"github.com/agent-wow/agent-wow/tools/internal/clientdata"
)

const destination = "modules/classic/internal/factions/templates_gen.go"

func main() {
	if len(os.Args) > 1 {
		fmt.Println("Usage: ./run factioncatalog:generate\nReads tmp/client-data-5875/FactionTemplate.dbc and writes " + destination + ".")
		return
	}
	data, err := generate(clientdata.ClassicDirectory)
	if err == nil {
		err = os.WriteFile(destination, data, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "generate faction catalogue:", err)
		os.Exit(1)
	}
	fmt.Printf("Generated %s (%d bytes)\n", destination, len(data))
}

// generate encodes every FactionTemplate row (mangos-classic DBCStructure.h
// FactionTemplateEntry: ID, faction, flags, group mask, friend mask, enemy
// mask, enemyFaction[4], friendFaction[4]).
func generate(directory string) ([]byte, error) {
	data, err := clientdata.Read(directory, "FactionTemplate.dbc")
	if err != nil {
		return nil, err
	}
	sum := fmt.Sprintf("%x", sha256.Sum256(data))
	if sum != clientdata.ClassicFactionSHA256 {
		return nil, fmt.Errorf("FactionTemplate.dbc checksum mismatch: %s", sum)
	}
	if len(data) < 20 || string(data[:4]) != "WDBC" {
		return nil, errors.New("expected a complete WDBC header")
	}
	count := binary.LittleEndian.Uint32(data[4:8])
	fields := binary.LittleEndian.Uint32(data[8:12])
	size := binary.LittleEndian.Uint32(data[12:16])
	if fields != 14 || size != 56 || 20+uint64(count)*56+uint64(binary.LittleEndian.Uint32(data[16:20])) != uint64(len(data)) {
		return nil, errors.New("unexpected FactionTemplate.dbc layout")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by ./run factioncatalog:generate; DO NOT EDIT.")
	fmt.Fprintln(&out, "// WoW 1.12.1, build 5875. Source: a cMaNGOS Classic server's DataDir/dbc.")
	fmt.Fprintf(&out, "// FactionTemplate.dbc: %d rows; SHA-256: %s\n", count, sum)
	fmt.Fprintln(&out, "\npackage factions")
	fmt.Fprintln(&out, "\nvar templates = map[uint32]Template{")
	for i := uint32(0); i < count; i++ {
		var row [14]uint32
		for j := range row {
			off := 20 + int(i)*56 + j*4
			row[j] = binary.LittleEndian.Uint32(data[off : off+4])
		}
		fmt.Fprintf(&out, "%d: {Faction: %d, Group: %d, Friends: %d, Enemies: %d, EnemyFactions: [4]uint32{%d, %d, %d, %d}, FriendFactions: [4]uint32{%d, %d, %d, %d}},\n",
			row[0], row[1], row[3], row[4], row[5], row[6], row[7], row[8], row[9], row[10], row[11], row[12], row[13])
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}
